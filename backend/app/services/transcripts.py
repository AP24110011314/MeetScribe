"""Transcript persistence (docs/DATABASE.md `transcripts`).

One row per meeting. The `search_vector` tsvector column is generated by the database from
`full_text` (see the initial migration), so it is never written here.
"""

import uuid

from sqlalchemy.ext.asyncio import AsyncSession

from app.db.models import Transcript
from app.services.transcription import Segment, full_text_from_segments


async def save_transcript(
    session: AsyncSession,
    meeting_id: uuid.UUID,
    *,
    segments: list[Segment],
    model: str,
) -> Transcript:
    """Insert or replace the meeting's transcript row (idempotent for retries)."""
    full_text = full_text_from_segments(segments)
    payload = [{"start": s.start, "end": s.end, "text": s.text} for s in segments]

    transcript = await session.get(Transcript, meeting_id)
    if transcript is None:
        transcript = Transcript(
            meeting_id=meeting_id,
            full_text=full_text,
            segments=payload,
            model=model,
        )
        session.add(transcript)
    else:
        transcript.full_text = full_text
        transcript.segments = payload
        transcript.model = model
    await session.flush()
    return transcript


async def get_transcript(session: AsyncSession, meeting_id: uuid.UUID) -> Transcript | None:
    """Return the meeting's transcript row, if transcription has completed."""
    return await session.get(Transcript, meeting_id)
